export function normaliseMake(value: string): string {
  const key = value
    .toLowerCase()
    .replace(/ä/g, "ae").replace(/ö/g, "oe").replace(/ü/g, "ue").replace(/ß/g, "ss")
    .normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return ALIASES[key] ?? key;
}

export const mobileDeMakeId = (make: string): number | null =>
  MOBILE_DE_MAKES[normaliseMake(make)] ?? null;
